/**
 * Rebuilds the hydrographic-basin reference table from speologie.org.
 *
 * The catalogue's API answers a cave's basin as a bare integer and publishes no way to turn that
 * integer into a name — so a cave imported from it would carry `bazinHidroId: 605` and nothing a
 * person could read. The names *are* public: the site's own basin page embeds the whole tree, 653
 * entries with their parents, in the page payload.
 *
 * This reads that page and regenerates `SpeologieBasinData.cs`. It exists as a script rather than
 * as something anybody does by hand because the page structure is not a documented interface: it
 * can change without notice, and when it does the refresh has to be repeatable, reviewable as a
 * diff, and obviously separate from code somebody wrote.
 *
 * Run with `node scripts/refresh-speologie-basins.mjs`. It needs no API key — the page is public —
 * and it makes exactly one request.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://www.speologie.org/bazine-hidro';
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'server', 'src', 'SilexGis.Domain', 'Catalogue', 'SpeologieBasinData.cs');

/**
 * The rows as the page embeds them. Matched on the whole object rather than field by field so a
 * page that changes shape yields nothing and fails loudly, instead of yielding half the tree.
 */
const ROW = new RegExp(
  String.raw`\\"id\\":(\d+),` +
    String.raw`\\"name\\":\\"((?:[^"\\]|\\.)*?)\\",` +
    String.raw`\\"weight\\":-?\d+,` +
    String.raw`\\"description\\":(?:null|\\".*?\\"),` +
    String.raw`\\"parent_id\\":(null|\d+),` +
    String.raw`\\"slug\\":\\"(?:[^"\\]|\\.)*?\\"`,
  'g',
);

const response = await fetch(SOURCE, { headers: { 'User-Agent': 'SilexGIS basin reference refresh' } });
if (!response.ok) {
  throw new Error(`${SOURCE} answered ${response.status}`);
}

const html = await response.text();
const rows = new Map();

for (const [, id, name, parent] of html.matchAll(ROW)) {
  rows.set(Number(id), {
    id: Number(id),
    name: name.replaceAll('\\"', '"').replaceAll('\\\\', '\\').trim(),
    parentId: parent === 'null' ? null : Number(parent),
  });
}

if (rows.size < 500) {
  throw new Error(
    `Only ${rows.size} basins were found, which is far fewer than the tree holds. ` +
      'The page has almost certainly changed shape — do not commit a truncated table.',
  );
}

const orphans = [...rows.values()].filter((r) => r.parentId !== null && !rows.has(r.parentId));
if (orphans.length > 0) {
  throw new Error(`${orphans.length} basins name a parent that is not in the tree; the read is incomplete.`);
}

const ordered = [...rows.values()].sort((a, b) => a.id - b.id);
const escape = (s) => s.replaceAll('\\', '\\\\').replaceAll('"', '\\"');

const body = ordered
  .map((r) => `        (${r.id}, ${r.parentId === null ? 'null' : r.parentId}, "${escape(r.name)}"),`)
  .join('\n');

writeFileSync(
  target,
  `// SPDX-License-Identifier: AGPL-3.0-or-later
// <auto-generated>
//     Regenerated by scripts/refresh-speologie-basins.mjs from ${SOURCE}.
//     Do not edit by hand: the next refresh would silently discard the edit.
// </auto-generated>

namespace SilexGis.Domain.Catalogue;

/// <summary>
/// The hydrographic basins of the Romanian cave catalogue, as that catalogue publishes them:
/// ${ordered.length} entries, each naming its parent, forming the tree a cave's basin identifier
/// points into.
/// </summary>
/// <remarks>
/// Carried here rather than fetched, because the catalogue's programmatic interface answers a
/// cave's basin as a bare integer and offers no way to resolve it. Refreshing this is a script,
/// not a request made while somebody waits — the tree changes about as often as a mountain does.
/// </remarks>
internal static class SpeologieBasinData
{
    /// <summary>Identifier, parent identifier, and the name exactly as the catalogue writes it.</summary>
    internal static readonly (int Id, int? ParentId, string Name)[] Rows =
    [
${body}
    ];
}
`,
  'utf8',
);

console.log(`Wrote ${ordered.length} basins to ${target}`);
