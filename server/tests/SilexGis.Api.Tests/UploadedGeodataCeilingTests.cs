using System.Buffers.Binary;
using System.Diagnostics;
using System.IO.Compression;
using System.Text;
using Microsoft.Extensions.Options;
using OSGeo.GDAL;
using OSGeo.OGR;
using OSGeo.OSR;
using Shouldly;
using SilexGis.Api.Tests.Support;
using SilexGis.Domain;
using SilexGis.Infrastructure.Geodata;

namespace SilexGis.Api.Tests;

/// <summary>
/// An uploaded vector or raster file that states it expands far beyond its own size is refused
/// from what it states, before the geodata library reads it — and the same shape within the
/// ceiling still reads. Every hostile file here is generated by the test: a few kilobytes on
/// disk that declare gigabytes, millions of features or billions of pixels.
/// </summary>
[Collection(RasterScratchCollection.Name)]
public sealed class UploadedGeodataCeilingTests : IDisposable
{
    private readonly string root = Path.Combine(
        TestScratch.Root, "silexgis-geodata-ceilings-" + Guid.NewGuid().ToString("N"));

    public UploadedGeodataCeilingTests()
    {
        Directory.CreateDirectory(root);
        GdalRuntime.Configure();
    }

    public void Dispose()
    {
        try
        {
            Directory.Delete(root, recursive: true);
        }
        catch (IOException)
        {
            // A temporary directory that outlives the run is not worth failing a test over.
        }
    }

    [Fact]
    public void A_zipped_shapefile_whose_entries_state_gigabytes_is_refused_before_it_is_read()
    {
        var honest = ZippedShapefile("honest.zip", points: 3);
        new GdalVectorIO().Read(honest, GeofileFormat.Shapefile).Features.Count.ShouldBe(3);

        var hostile = Path.Combine(root, "hostile.zip");
        var bytes = File.ReadAllBytes(honest);
        StateLength(bytes, ".dbf", 2_000_000_000);
        File.WriteAllBytes(hostile, bytes);
        new FileInfo(hostile).Length.ShouldBeLessThan(10_000);

        Should.Throw<VectorIOException>(() => new GdalVectorIO().Read(hostile, GeofileFormat.Shapefile))
            .Message.ShouldContain("expands to more than this server reads");
    }

    [Fact]
    public void A_kmz_whose_document_states_gigabytes_is_refused_and_one_within_the_ceiling_reads()
    {
        var honest = Path.Combine(root, "places.kmz");
        Zip(honest, ("doc.kml", Kml(points: 2)));
        new GdalVectorIO().Read(honest, GeofileFormat.Kmz).Features.Count.ShouldBe(2);

        var hostile = Path.Combine(root, "hostile.kmz");
        var bytes = File.ReadAllBytes(honest);
        StateLength(bytes, "doc.kml", 3_000_000_000);
        File.WriteAllBytes(hostile, bytes);

        Should.Throw<VectorIOException>(() => new GdalVectorIO().Read(hostile, GeofileFormat.Kmz))
            .Message.ShouldContain("expands to more than this server reads");
    }

    [Fact]
    public void A_kmz_crowded_with_empty_entries_is_refused_before_its_directory_is_built()
    {
        // One more entry than any geodata archive holds, all of them empty: a few hundred
        // kilobytes on disk. Scaled to millions, the runtime's directory objects alone would cost
        // gigabytes before any cap that counts them after opening the archive got to say no.
        var crowded = Path.Combine(root, "crowded.kmz");
        Zip(crowded, ("doc.kml", Kml(points: 2)));
        Crowd(crowded, ArchiveFormatSniffer.MaxArchiveEntries);
        new FileInfo(crowded).Length.ShouldBeLessThan(2 * 1024 * 1024);

        Should.Throw<VectorIOException>(() => new GdalVectorIO().Read(crowded, GeofileFormat.Kmz))
            .Message.ShouldContain($"more than {ArchiveFormatSniffer.MaxArchiveEntries:N0} files");
        Should.Throw<VectorIOException>(() => new GdalVectorIO().Read(crowded, GeofileFormat.Shapefile))
            .Message.ShouldContain($"more than {ArchiveFormatSniffer.MaxArchiveEntries:N0} files");
    }

    [Fact]
    public void The_upload_request_tells_the_zipped_formats_apart_but_does_not_open_a_crowded_archive()
    {
        var kmz = Path.Combine(root, "places.zip");
        Zip(kmz, ("doc.kml", Kml(points: 2)));
        ArchiveFormatSniffer.Detect(kmz).ShouldBe(GeofileFormat.Kmz);
        ArchiveFormatSniffer.Detect(ZippedShapefile("shapes.zip", points: 2)).ShouldBe(GeofileFormat.Shapefile);

        // The same KMZ with more entries than a geodata archive holds is left undecided: the
        // upload keeps the format its name gave it, and the import job refuses it by name.
        Crowd(kmz, ArchiveFormatSniffer.MaxArchiveEntries);
        ArchiveFormatSniffer.Detect(kmz).ShouldBeNull();
    }

    [Fact]
    public void A_kmz_document_past_the_configured_ceiling_is_refused_and_one_within_it_reads()
    {
        var upload = Path.Combine(root, "big.kmz");
        Zip(upload, ("doc.kml", Kml(points: 200)));

        var reader = Reader(new UploadedGeodataOptions { MaxKmzDocumentBytes = 1024 });
        Should.Throw<VectorIOException>(() => reader.Read(upload, GeofileFormat.Kmz))
            .Message.ShouldContain("expands to more than this server reads");

        Reader(new UploadedGeodataOptions()).Read(upload, GeofileFormat.Kmz).Features.Count.ShouldBe(200);
    }

    [Fact]
    public void A_file_holding_more_features_than_the_ceiling_is_refused_and_one_at_it_reads()
    {
        var reader = Reader(new UploadedGeodataOptions { MaxFeatures = 10 });

        var atCeiling = Path.Combine(root, "ten.geojson");
        File.WriteAllText(atCeiling, GeoJson(points: 10));
        reader.Read(atCeiling, GeofileFormat.GeoJson).Features.Count.ShouldBe(10);

        var over = Path.Combine(root, "eleven.geojson");
        File.WriteAllText(over, GeoJson(points: 11));
        Should.Throw<VectorIOException>(() => reader.Read(over, GeofileFormat.GeoJson))
            .Message.ShouldContain("more than 10 features");
    }

    [Fact]
    public void A_sparse_geotiff_stating_ten_billion_pixels_is_refused_in_seconds_not_converted()
    {
        var hostile = GeoTiff(Path.Combine(root, "sparse.tif"), 100_000, 100_000, sparse: true);
        new FileInfo(hostile).Length.ShouldBeLessThan(5_000_000);

        var service = new RasterCogService();
        var output = Path.Combine(root, "out", "sparse-cog.tif");
        var clock = Stopwatch.StartNew();
        Should.Throw<VectorIOException>(() => service.ConvertToCog(hostile, output))
            .Message.ShouldContain("more than this server converts");
        clock.Elapsed.ShouldBeLessThan(TimeSpan.FromSeconds(30));
        File.Exists(output).ShouldBeFalse();

        // Placed or not, it is never handed to the sheet path as a scan to draw.
        service.IsUnplacedRaster(hostile).ShouldBeFalse();
    }

    [Fact]
    public void A_raster_past_a_configured_ceiling_is_refused_and_one_within_it_converts()
    {
        var map = GeoTiff(Path.Combine(root, "map.tif"), 64, 64, sparse: false);

        var tight = new RasterCogService(Options.Create(new UploadedGeodataOptions { MaxRasterPixelValues = 64 * 64 - 1 }));
        Should.Throw<VectorIOException>(() => tight.ConvertToCog(map, Path.Combine(root, "out", "tight.tif")));

        var loose = new RasterCogService(Options.Create(new UploadedGeodataOptions { MaxRasterPixelValues = 64 * 64 }));
        loose.ConvertToCog(map, Path.Combine(root, "out", "loose.tif")).Width.ShouldBe(64);
    }

    private static GdalVectorIO Reader(UploadedGeodataOptions options) => new(Options.Create(options));

    /// <summary>
    /// Rewrites the uncompressed length an archive states for every entry whose name ends with
    /// <paramref name="nameSuffix"/>, in its local header and its central-directory record.
    /// The bytes themselves are untouched: this is the "tiny on disk, huge declared" shape.
    /// </summary>
    private static void StateLength(byte[] zip, string nameSuffix, uint length)
    {
        var patched = 0;
        for (var i = 0; i + 46 <= zip.Length; i++)
        {
            var signature = BinaryPrimitives.ReadUInt32LittleEndian(zip.AsSpan(i));
            if (signature == 0x02014b50)
            {
                var nameLength = BinaryPrimitives.ReadUInt16LittleEndian(zip.AsSpan(i + 28));
                var name = Encoding.UTF8.GetString(zip, i + 46, nameLength);
                if (name.EndsWith(nameSuffix, StringComparison.Ordinal))
                {
                    BinaryPrimitives.WriteUInt32LittleEndian(zip.AsSpan(i + 24), length);
                    patched++;
                }
            }
            else if (signature == 0x04034b50)
            {
                var nameLength = BinaryPrimitives.ReadUInt16LittleEndian(zip.AsSpan(i + 26));
                var name = Encoding.UTF8.GetString(zip, i + 30, nameLength);
                if (name.EndsWith(nameSuffix, StringComparison.Ordinal))
                {
                    BinaryPrimitives.WriteUInt32LittleEndian(zip.AsSpan(i + 22), length);
                }
            }
        }

        patched.ShouldBeGreaterThan(0, $"no entry ending {nameSuffix}");
    }

    private string ZippedShapefile(string name, int points)
    {
        var folder = Path.Combine(root, Path.GetFileNameWithoutExtension(name));
        Directory.CreateDirectory(folder);
        using (var source = Ogr.GetDriverByName("ESRI Shapefile").CreateDataSource(Path.Combine(folder, "points.shp"), null))
        using (var reference = new SpatialReference(""))
        {
            reference.ImportFromEPSG(4326);
            var layer = source.CreateLayer("points", reference, wkbGeometryType.wkbPoint, null);
            layer.CreateField(new FieldDefn("label", FieldType.OFTString), 1);
            for (var i = 0; i < points; i++)
            {
                using var feature = new Feature(layer.GetLayerDefn());
                feature.SetField("label", $"p{i}");
                using var point = new OSGeo.OGR.Geometry(wkbGeometryType.wkbPoint);
                point.AddPoint_2D(25.0 + ((i + 1) / 10.0), 46.1);
                feature.SetGeometry(point);
                layer.CreateFeature(feature);
            }
        }

        var archive = Path.Combine(root, name);
        ZipFile.CreateFromDirectory(folder, archive);
        return archive;
    }

    /// <summary>Adds <paramref name="count"/> empty entries to an existing archive.</summary>
    private static void Crowd(string path, int count)
    {
        using var archive = ZipFile.Open(path, ZipArchiveMode.Update);
        for (var i = 0; i < count; i++)
        {
            archive.CreateEntry($"e/{i}");
        }
    }

    private static void Zip(string path, params (string Name, string Content)[] entries)
    {
        using var archive = ZipFile.Open(path, ZipArchiveMode.Create);
        foreach (var (name, content) in entries)
        {
            using var writer = new StreamWriter(archive.CreateEntry(name).Open());
            writer.Write(content);
        }
    }

    private static string Kml(int points)
    {
        var placemarks = new StringBuilder();
        for (var i = 0; i < points; i++)
        {
            placemarks.Append(
                $"<Placemark><name>p{i}</name><Point><coordinates>25.{i + 1},46.1</coordinates></Point></Placemark>");
        }

        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>"
            + "<kml xmlns=\"http://www.opengis.net/kml/2.2\"><Document>"
            + placemarks
            + "</Document></kml>";
    }

    private static string GeoJson(int points) =>
        "{\"type\":\"FeatureCollection\",\"features\":["
        + string.Join(",", Enumerable.Range(0, points).Select(i =>
            "{\"type\":\"Feature\",\"properties\":{},"
            + $"\"geometry\":{{\"type\":\"Point\",\"coordinates\":[25.{i + 1},46.1]}}}}"))
        + "]}";

    private static string GeoTiff(string path, int width, int height, bool sparse)
    {
        string[] creation = sparse
            ? ["SPARSE_OK=TRUE", "TILED=YES", "BLOCKXSIZE=512", "BLOCKYSIZE=512", "COMPRESS=DEFLATE", "BIGTIFF=NO"]
            : [];
        using (var dataset = Gdal.GetDriverByName("GTiff").Create(path, width, height, 1, DataType.GDT_Byte, creation))
        {
            dataset.SetGeoTransform([25.0, 0.0001, 0, 46.06, 0, -0.0001]);
            using var reference = new SpatialReference("");
            reference.ImportFromEPSG(4326);
            reference.ExportToWkt(out var wkt, null);
            dataset.SetProjection(wkt);
        }

        return path;
    }
}
